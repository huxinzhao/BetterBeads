def weapon(x,y,metal):
 global im,d
 begin();src=weapons.crop((x*17,y*17,x*17+16,y*17+16))
 for py in range(16):
  for px in range(16):
   rr,gg,bb,aa=src.getpixel((px,py))
   if rr==gg==bb and rr>=150:continue
   if rr==gg==bb and rr<70:c='D'
   elif rr>180 and gg>180:c=metal[(px+py)%3!=0]
   elif rr>180 and gg>100:c='Y'
   elif rr>100:c='b' if (px+py)%2 else 'B'
   else:c='D'
   p(px,py,c)
 # shaded edge and pale cutting face for a readable slanting blade
 return im
