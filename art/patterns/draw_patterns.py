def crop_tile(x,y):
 src=crop_sheet.crop((x*16,y*16,(x+1)*16,(y+1)*16))
 for y in range(16):
  for x in range(16):
   rr,gg,bb,aa=src.getpixel((x,y))
   if not aa:src.putpixel((x,y),(0,0,0,0));continue
   hh,ss,vv=colorsys.rgb_to_hsv(rr/255,gg/255,bb/255)
   # Lift the very dark source ramps; retain its hand-drawn clusters.
   vv=min(1,vv*.93+.10);ss*=.83
   if .20<hh<.48:hh=.30+(hh-.30)*.65
   rgb=tuple(round(v*255) for v in colorsys.hsv_to_rgb(hh,ss,vv))
   src.putpixel((x,y),rgb+(255,))
 return src
